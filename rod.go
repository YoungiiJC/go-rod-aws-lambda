		go browser.MustHandleAuth(username, proxyPassword)()
		time.Sleep(3 * time.Second)

		browser.Page(proto.TargetCreateTarget{})
		browser.MustIgnoreCertErrors(true)
		page := stealth.MustPage(browser)

		// open a page

